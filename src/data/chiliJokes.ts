const headingPatterns = [
  /^here is the definitive/i,
  /^note:/i,
  /^###\s+/i,
];

function seededShuffle<T>(arr: T[]) {
  const result = [...arr];
  let seed = 1771;
  for (let i = result.length - 1; i > 0; i -= 1) {
    seed = (seed * 48271) % 0x7fffffff;
    const j = seed % (i + 1);
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

// Parse lines into category buckets and interleave for variety
const lines = RAW_CHILI.split('\n').map((line) => line.trim()).filter(Boolean);

type Buckets = Record<string, string[]>;
const buckets: Buckets = {};
let currentCategory = 'General';

const numberStripper = /^\d+\.\s*/;

lines.forEach((line) => {
  if (headingPatterns.some((re) => re.test(line))) {
    if (line.startsWith('###')) {
      currentCategory = line.replace(/^###\s+/, '').trim() || 'General';
    }
    return;
  }

  const cleaned = line.replace(numberStripper, '').trim();
  if (!cleaned) return;
  if (!buckets[currentCategory]) buckets[currentCategory] = [];
  buckets[currentCategory].push(cleaned);
});

// Interleave categories to avoid streaks
const categoryOrder = seededShuffle(Object.keys(buckets));
const categoryPools = categoryOrder.map((cat) => ({
  cat,
  jokes: seededShuffle(buckets[cat]),
}));

const interleaved: string[] = [];
let remaining = categoryPools.reduce((sum, pool) => sum + pool.jokes.length, 0);

while (remaining > 0) {
  // Rotate through categories in shuffled order
  categoryPools.forEach((pool) => {
    if (pool.jokes.length > 0) {
      interleaved.push(pool.jokes.shift() as string);
      remaining -= 1;
    }
  });
}

export const CHILI_JOKES = interleaved;
